function Y = vMFrnd(n, mu, kappa)
%vMFrnd generates random unit vectors from the von Mises-Fisher distribution in any dimension
%
%<a href="matlab: docsearchFS('vMFrnd')">Link to the help page for this function</a>
%
%   vMFrnd returns an n-by-p matrix whose rows are independent draws from
%   the von Mises-Fisher distribution vMF(mu,kappa) on the unit
%   hypersphere S^(p-1) in R^p, with density
%
%     f(y; mu, kappa) = C_p(kappa) * exp(kappa * mu' * y),
%
%   where mu (a unit vector) is the mean direction and kappa>=0 is the
%   concentration parameter. The dimension p is the length of mu and can
%   be any integer greater than or equal to 2: p=2 gives the von Mises
%   distribution on the circle, p=3 the Fisher distribution on the
%   sphere, large p the setting of document embeddings. The sample is
%   exact: it is obtained with the acceptance-rejection algorithm of Wood
%   (1994), whose acceptance rate is high for every p and kappa.
%
%   vMFrnd is the vMF counterpart of Kentrnd: data generated by vMFrnd
%   form a "circular cap" around mu, while those generated by Kentrnd
%   (p=3 only) form an "elliptical cap".
%
%  Required input arguments:
%
%            n: Number of random vectors. Scalar. Positive integer.
%           mu: Mean direction. Vector of length p (p>=2). It is rescaled
%               to unit norm. Its length defines the dimension of the
%               space.
%        kappa: Concentration parameter. Scalar. kappa>=0. kappa=0 gives
%               the uniform distribution on S^(p-1). For large kappa the
%               distribution of the data around mu is approximately
%               normal with covariance matrix (1/kappa)*I on the tangent
%               space.
%
%  Optional input arguments:
%
%  Output:
%
%            Y: Random sample. Matrix. n-by-p matrix of unit vectors, one
%               draw from vMF(mu,kappa) per row.
%
% More About:
%
% ALGORITHM (Ulrich, 1984; Wood, 1994)
%
% A vMF vector with mean direction e_p=(0,...,0,1) can be written as
%
%     y = ( sqrt(1-w^2)*v , w ),
%
% where v is uniformly distributed on S^(p-2) and w=e_p'*y, independent
% of v, has density proportional to exp(kappa*w)*(1-w^2)^((p-3)/2) on
% [-1,1]. The scalar w is generated by acceptance-rejection: with
%
%     b  = (p-1)/(2*kappa + sqrt(4*kappa^2+(p-1)^2)),
%     x0 = (1-b)/(1+b),    c = kappa*x0 + (p-1)*log(1-x0^2),
%
% draw z from Beta((p-1)/2,(p-1)/2) and u from U(0,1), put
% w=(1-(1+b)*z)/(1-(1-b)*z) and accept w if
%
%     kappa*w + (p-1)*log(1-x0*w) - c >= log(u).
%
% Finally the vector is moved from e_p to mu with the Householder
% reflection which exchanges e_p and mu (the vMF distribution is
% symmetric around its mean direction, so a reflection can be used in
% place of a rotation).
%
% References:
%
%   Ulrich, G. (1984), Computer generation of distributions on the
%   m-sphere, Applied Statistics, Vol. 33, pp. 158-163.
%
%   Wood, A.T.A. (1994), Simulation of the von Mises Fisher distribution,
%   Communications in Statistics - Simulation and Computation, Vol. 23,
%   pp. 157-164.
%
%   Mardia, K.V. and Jupp, P.E. (2000), Directional Statistics, Wiley,
%   Chichester.
%
% See also: Kentrnd, sphereplot, tclustvmf, logvMFpdfFS, kappaFS, vMFcap
%
% Copyright 2008-2025.
% Written by FSDA team
%
%<a href="matlab: docsearchFS('vMFrnd')">Link to the help page for this function</a>
%
%$LastChangedDate::                      $: Date of the last commit
%
% Examples:
%
%{
    %% A circular cap on the sphere (p=3).
    % 500 draws from a vMF distribution with mean direction [1 0 0],
    % plotted with the 95 per cent confidence cap.
    rng(1)
    mu = [1 0 0]; kappa = 30;
    Y = vMFrnd(500, mu, kappa);
    sphereplot(Y, 'cap', struct('mu',mu,'kappa',kappa));
%}
%
%{
    %% von Mises data on the circle (p=2).
    rng(2)
    mu = [1 1]; kappa = 8;
    Y = vMFrnd(300, mu, kappa);
    sphereplot(Y, 'cap', struct('mu',mu,'kappa',kappa));
%}
%
%{
    % Check in high dimension: the mean resultant length.
    % The length of the mean vector of the sample is close to
    % A_p(kappa)=I_{p/2}(kappa)/I_{p/2-1}(kappa), and kappaFS recovers
    % kappa from it.
    rng(3)
    p = 50; kappa = 100;
    mu = ones(1,p);
    Y = vMFrnd(20000, mu, kappa);
    r = norm(mean(Y,1));
    Ap = besseli(p/2,kappa,1)/besseli(p/2-1,kappa,1);
    fprintf('Mean resultant length: %.4f, A_p(kappa): %.4f\n', r, Ap);
    fprintf('kappa: true %g, estimated with kappaFS %.2f\n', kappa, kappaFS(r,p));
%}
%
%{
    % kappa=0: uniform distribution on the sphere.
    rng(4)
    Y = vMFrnd(1000, [0 0 1], 0);
    sphereplot(Y);
%}
%
%{
    % Two vMF groups in dimension p=100 analysed with tclustvmf.
    rng(5)
    p = 100; n = 200;
    mu1 = zeros(1,p); mu1(1) = 1;
    mu2 = zeros(1,p); mu2(2) = 1;
    Y = [vMFrnd(n, mu1, 300); vMFrnd(n, mu2, 150)];
    out = tclustvmf(Y, 2, 0.05, 50, 'msg', 0);
    disp('True kappa 300 and 150. Estimated kappa:'); disp(out.kappaopt')
%}

%% Beginning of code

if nargin < 3
    error('FSDA:vMFrnd:missingInputs', 'n, mu and kappa must be supplied')
end
if kappa < 0
    error('FSDA:vMFrnd:WrongKappa', 'kappa must be non-negative')
end
mu = mu(:)';
p = numel(mu);
if p < 2
    error('FSDA:vMFrnd:WrongMu', 'mu must have at least 2 elements')
end
normmu = norm(mu);
if normmu < 1e-12
    error('FSDA:vMFrnd:WrongMu', 'mu must not be the null vector')
end
mu = mu/normmu;

% kappa=0: uniform distribution on S^(p-1)
if kappa == 0
    Y = randn(n, p);
    Y = Y./sqrt(sum(Y.^2, 2));
    return
end

% Component w along the mean direction (Wood, 1994). b is written in a
% form which does not suffer from cancellation when kappa is large.
b  = (p-1)/(2*kappa + sqrt(4*kappa^2 + (p-1)^2));
x0 = (1-b)/(1+b);
c  = kappa*x0 + (p-1)*log(1 - x0^2);

w = zeros(n, 1);
nacc = 0;
while nacc < n
    m = ceil(1.5*(n-nacc)) + 20;
    z = betarnd((p-1)/2, (p-1)/2, m, 1);
    u = rand(m, 1);
    wprop = (1 - (1+b)*z)./(1 - (1-b)*z);
    acc = kappa*wprop + (p-1)*log(1 - x0*wprop) - c >= log(u);
    idx = find(acc, n-nacc);
    na = numel(idx);
    w(nacc+1:nacc+na) = wprop(idx);
    nacc = nacc + na;
end
w = min(max(w, -1), 1);

% Uniform direction on S^(p-2), orthogonal to the mean direction
V = randn(n, p-1);
V = V./sqrt(sum(V.^2, 2));

% Sample with mean direction e_p
Y = [sqrt(1 - w.^2).*V, w];

% Householder reflection which exchanges e_p and mu
u = -mu;
u(p) = u(p) + 1;
normu = norm(u);
if normu > 1e-12
    u = u/normu;
    Y = Y - 2*(Y*u')*u;
end

end
